def test_values_are_those_of_jax_scipy():
    table = _reference_table("FIRST_ORDER")
    a, b, x = table[:, :3].T
    np.testing.assert_array_equal(betainc(a, b, x), jax_betainc(a, b, x))
    np.testing.assert_allclose(betainc(a, b, x), table[:, 3], rtol=1e-9)


def test_first_derivatives_match_mpmath_table():
    table = _reference_table("FIRST_ORDER")
    _, ia, ib, ix = _value_and_partials(*table[:, :3].T)
    _assert_rel_close(ia, table[:, 4], 1e-10, "dI/da")
    _assert_rel_close(ib, table[:, 5], 1e-10, "dI/db")
    _assert_rel_close(ix, table[:, 6], 1e-12, "dI/dx")


def test_second_derivatives_match_mpmath_table():
    table = _reference_table("SECOND_ORDER")
    a, b, x = table[:, :3].T
    hess = jax.jit(jax.vmap(jax.hessian(lambda v: betainc(v[0], v[1], v[2]))))
    h = np.asarray(hess(jnp.stack([a, b, x], axis=1)))
    # I_ab vanishes at a = b, x = 1/2; measure it against the (a, b)-block
    scale = np.abs(table[:, 3:6]).max(axis=1) * 1e-4
    for (i, j), col, rtol in (
        ((0, 0), 3, 1e-9),
        ((0, 1), 4, 1e-9),
        ((1, 0), 4, 1e-9),
        ((1, 1), 5, 1e-9),
        ((0, 2), 6, 1e-9),
        ((1, 2), 7, 1e-9),
        ((2, 2), 8, 1e-11),
    ):
        _assert_rel_close(h[:, i, j], table[:, col], rtol, f"hessian[{i}, {j}]", scale)


def test_first_derivatives_match_mpmath_at_random_points():
    pytest.importorskip("mpmath")
    rng = np.random.default_rng(20261114)
    n = 150
    a = np.exp(rng.uniform(np.log(1e-3), np.log(120.0), n))
    b = np.exp(rng.uniform(np.log(1e-3), np.log(30.0), n))
    x = np.concatenate(
        [
            rng.uniform(size=n // 3),
            np.exp(rng.uniform(np.log(1e-12), 0.0, n // 3)),
            _switch(a, b)[: n - 2 * (n // 3)] * (1 + rng.normal(scale=0.02, size=n - 2 * (n // 3))),
        ]
    )
    x = np.clip(x, 1e-12, 1 - 1e-12)
    want = np.array([_mpmath_partials(*p, order=1) for p in zip(a, b, x)])
    _, ia, ib, ix = _value_and_partials(a, b, x)
    _assert_rel_close(ia, want[:, 1], 1e-10, "dI/da")
    _assert_rel_close(ib, want[:, 2], 1e-10, "dI/db")
    _assert_rel_close(ix, want[:, 3], 1e-12, "dI/dx")


@pytest.mark.parametrize(
    "a, b, x",
    [(0.7, 2.3, 0.4), (25.0, 0.3, 0.9), (0.05, 8.0, 0.02), (3.0, 3.0, 0.6), (65.5, 0.6, 0.999)],
)
def test_check_grads_second_order(a, b, x):
    check_grads(jax.jit(betainc), (a, b, x), order=2, modes=("fwd", "rev"), eps=1e-6, rtol=1e-5)


def test_higher_order_modes_agree():
    a, b, x = 4.0, 0.4, 0.8
    f = lambda v: betainc(v[0], v[1], v[2])
    v = jnp.array([a, b, x])
    hessian = jax.jit(jax.hessian(f))
    fwd_rev = hessian(v)
    np.testing.assert_allclose(jax.jit(jax.jacrev(jax.jacrev(f)))(v), fwd_rev, rtol=1e-12)
    np.testing.assert_allclose(jax.jit(jax.jacfwd(jax.jacfwd(f)))(v), fwd_rev, rtol=1e-12)
    grad_grad = jax.jit(jax.grad(jax.grad(betainc, 1), 1))
    np.testing.assert_allclose(grad_grad(a, b, x), fwd_rev[1, 1], rtol=1e-12)
    # third order: a-derivative of the (a, b)-hessian
    check_grads(
        lambda a_: hessian(v.at[0].set(a_))[:2, :2], (a,),
        order=1, modes=("fwd",), eps=1e-5, rtol=1e-6, atol=0.0,
    )


