def test_broadcasting_jit_and_vmap():
    a = jnp.array([0.5, 4.0, 60.0]).reshape(3, 1, 1)
    b = jnp.array([0.2, 1.0, 2.5, 9.0]).reshape(1, 4, 1)
    x = jnp.linspace(0.05, 0.95, 5)
    out = jax.jit(betainc)(a, b, x)
    assert out.shape == (3, 4, 5)
    np.testing.assert_array_equal(out, jax_betainc(a, b, x))

    loss = lambda a, b, x: (betainc(a, b, x) ** 2).sum()
    grads = jax.jit(jax.grad(loss, argnums=(0, 1, 2)))(a, b, x)
    assert [g.shape for g in grads] == [a.shape, b.shape, x.shape]
    full = jnp.broadcast_arrays(a, b, x)
    full_grads = jax.grad(loss, argnums=(0, 1, 2))(*full)
    for g, fg, shape in zip(grads, full_grads, (a.shape, b.shape, x.shape)):
        fg = fg.sum(axis=tuple(range(fg.ndim - len(shape))))
        fg = fg.sum(axis=tuple(i for i, s in enumerate(shape) if s == 1), keepdims=True)
        np.testing.assert_allclose(g, fg, rtol=1e-13)

    per_point = jax.vmap(jax.vmap(jax.vmap(jax.grad(betainc, argnums=(0, 1)))))(*full)
    jac = jax.jacrev(lambda a_: betainc(a_, full[1], full[2]))(full[0])
    np.testing.assert_allclose(per_point[0], jnp.einsum("ijkijk->ijk", jac), rtol=1e-12)


def test_float32_matches_float64():
    table = _reference_table("FIRST_ORDER")
    inputs32 = table[:, :3].astype(np.float32)
    keep = (inputs32[:, 2] > 0) & (inputs32[:, 2] < 1)
    inputs32 = inputs32[keep]
    got = _value_and_partials(*(jnp.asarray(c) for c in inputs32.T))
    want = _value_and_partials(*(jnp.asarray(c, jnp.float64) for c in inputs32.T))
    assert all(g.dtype == np.float32 for g in got)
    assert not any(np.isnan(g).any() for g in got)
    np.testing.assert_array_equal(got[0], jax_betainc(*inputs32.T))
    for name, g, w in zip(("dI/da", "dI/db", "dI/dx"), got[1:], want[1:]):
        rel = np.abs(g - w) / np.maximum(np.abs(w), 1e-30)
        assert np.median(rel) < 1e-5, name
        assert np.max(rel[np.abs(w) > 1e-30]) < 1e-2, name


def test_integer_inputs_promote_to_default_float():
    assert betainc(2, 3, 0).dtype == jnp.float64
    np.testing.assert_allclose(jax.grad(betainc, argnums=2)(2.0, 3, 0.5), 12 * 0.5 * 0.25)


def test_complex_inputs_raise():
    with pytest.raises(ValueError):
        betainc(1.0, 1.0, 0.5 + 0j)


