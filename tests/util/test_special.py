@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_end_points(dtype):
    a = jnp.array([0.5, 1.0, 2.0, 0.5, 1.0, 2.0], dtype)
    b = jnp.array([0.5, 1.0, 2.0, 0.5, 1.0, 2.0], dtype)
    x = jnp.array([0.0, 0.0, 0.0, 1.0, 1.0, 1.0], dtype)
    value, ia, ib, ix = _value_and_partials(a, b, x)
    np.testing.assert_array_equal(value, [0, 0, 0, 1, 1, 1])
    np.testing.assert_array_equal(ia, 0.0)
    np.testing.assert_array_equal(ib, 0.0)
    # one-sided density limits: inf, 1 / B(1, 1) = 1, 0
    np.testing.assert_allclose(ix, [np.inf, 1.0, 0.0, np.inf, 1.0, 0.0], rtol=1e-6)


def test_infinite_density_does_not_reach_parameter_gradients():
    # x = 1 with b < 1 has an infinite x-derivative; it must not turn into
    # inf * 0 when only a and b are differentiated
    grad_ab = jax.grad(lambda a, b: betainc(a, b, 1.0), argnums=(0, 1))(2.0, 0.5)
    assert grad_ab == (0.0, 0.0)
    hess_ab = jax.hessian(lambda v: betainc(v[0], v[1], 0.0))(jnp.array([0.5, 3.0]))
    np.testing.assert_array_equal(hess_ab, 0.0)


def test_masked_zero_shape_parameter_keeps_gradients_finite():
    # a = (n - 1) beta vanishes for n = 1, where callers mask the result
    n = jnp.array([1.0, 2.0, 3.0])

    def masked(beta):
        vals = betainc((n - 1) * beta, beta, 0.4)
        return jnp.where(n == 1, 0.0, vals).sum()

    grad = jax.grad(masked)(0.3)
    assert np.isfinite(grad)
    np.testing.assert_allclose(
        grad, jax.grad(lambda beta: sum(betainc(k * beta, beta, 0.4) for k in (1.0, 2.0)))(0.3), rtol=1e-14
    )


def test_one_sided_derivative_at_zero_shape_parameter():
    # 1 - I_x(a, 2) ~ a * int_0^{1-x} t / (1-t) dt = -a * (1 - x + log x) as a -> 0
    x = 0.3
    want = 1 - x + np.log(x)
    np.testing.assert_allclose(jax.grad(betainc)(0.0, 2.0, x), want, rtol=1e-12)
    np.testing.assert_allclose(jax.grad(betainc)(1e-9, 2.0, x), want, rtol=1e-8)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_no_nan_derivatives_in_domain(dtype):
    tiny = 1e-300 if dtype == jnp.float64 else 1e-30
    params = (0.0, 1e-3, 0.3, 1.0, 2.0, 30.0, 120.0, 1e3)
    xs = (0.0, tiny, 1e-12, 0.3, 0.5, 0.97, 1 - 1e-7, 1.0)
    grid = np.array([(a, b, x) for a in params for b in params for x in xs if a + b > 0])
    a, b, x = (jnp.asarray(c, dtype) for c in grid.T)
    value, ia, ib, ix = _value_and_partials(a, b, x)
    assert value.dtype == dtype and ia.dtype == dtype
    assert np.all(np.isfinite(ia)) and np.all(np.isfinite(ib))
    assert not np.any(np.isnan(ix))
    # infinite x-derivatives only at end points with a < 1 (x = 0) or b < 1 (x = 1)
    x_cast = np.asarray(x)
    singular = ((x_cast == 0) & (grid[:, 0] < 1)) | ((x_cast == 1) & (grid[:, 1] < 1))
    assert np.all(np.isfinite(ix[~singular]))
    hess = jax.jit(jax.vmap(jax.hessian(lambda v, x_: betainc(v[0], v[1], x_))))
    h = np.asarray(hess(jnp.stack([a, b], axis=1), x))
    assert np.all(np.isfinite(h))


def test_out_of_domain_is_nan():
    a = jnp.array([-1.0, 2.0, 2.0, 2.0, 0.0, jnp.nan])
    b = jnp.array([2.0, -1.0, 2.0, 2.0, 0.0, 2.0])
    x = jnp.array([0.5, 0.5, -0.1, 1.1, 0.5, 0.5])
    value, ia, ib, ix = _value_and_partials(a, b, x)
    assert np.all(np.isnan(value))
    assert np.all(np.isnan(ia)) and np.all(np.isnan(ib)) and np.all(np.isnan(ix))


