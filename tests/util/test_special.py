"""
Regularised incomplete beta function with derivatives in ``a``, ``b`` and ``x``.

Values must be those of `jax.scipy.special.betainc`; derivatives are checked
against 40-digit mpmath references stored in `betainc_reference.py`
(regenerate with ``PYTHONPATH=src python tests/util/test_special.py``) and,
when mpmath is installed, against fresh references at random points.
"""
from jax import config

config.update("jax_enable_x64", True)

from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest
from jax.scipy.special import betainc as jax_betainc
from jax.test_util import check_grads

from tensordev.util.special import betainc

# a- and b-grids of the stored first-order table
_TABLE_A = (1e-3, 0.1, 1.0, 7.0, 40.0, 120.0)
_TABLE_B = (1e-3, 0.1, 0.7, 3.0, 30.0)
# a- and b-grids of the stored second-order table
_TABLE2_A = (1e-3, 1.0, 40.0, 120.0)
_TABLE2_B = (1e-3, 0.7, 30.0)


def _switch(a, b):
    """x = (a + 1) / (a + b + 2); above it betainc evaluates 1 - I_{1-x}(b, a)."""
    return (a + 1) / (a + b + 2)


def _first_order_points():
    for a in _TABLE_A:
        for b in _TABLE_B:
            s = _switch(a, b)
            for x in (1e-10, 0.05, 0.5, 1 - 1e-7, s * (1 - 1e-3), s * (1 + 1e-3)):
                yield a, b, x
    # Volterra usage: a = rho + (n - 1) beta + 1 + j, b = beta
    for beta in (0.1, 0.6, 2.5):
        for j in (0, 64):
            for x in (0.3, 0.999):
                yield 0.5 + 2 * beta + 1 + j, beta, x


def _second_order_points():
    for a in _TABLE2_A:
        for b in _TABLE2_B:
            for x in (0.05, 0.5, 0.97, _switch(a, b) * (1 + 1e-3)):
                yield a, b, x


def _mpmath_partials(a, b, x, order):
    """All partials of I_x(a, b) of the given order at 40 digits.

    order 1: (I, I_a, I_b, I_x); order 2: (I_aa, I_ab, I_bb, I_ax, I_bx, I_xx).
    The (a, b)-derivatives are taken of whichever of I and 1 - I is smaller,
    so that they keep full relative precision.
    """
    import mpmath

    mpmath.mp.dps = 40
    a, b, x = (mpmath.mpf(v) for v in (a, b, x))
    value = mpmath.betainc(a, b, 0, x, regularized=True)
    if value <= 0.5:
        sign, smaller = 1, lambda a_, b_: mpmath.betainc(a_, b_, 0, x, regularized=True)
    else:
        sign, smaller = -1, lambda a_, b_: mpmath.betainc(b_, a_, 0, 1 - x, regularized=True)

    def density(a_, b_, x_=x):
        return mpmath.exp(
            (a_ - 1) * mpmath.log(x_) + (b_ - 1) * mpmath.log(1 - x_) - mpmath.log(mpmath.beta(a_, b_))
        )

    if order == 1:
        out = [value] + [sign * mpmath.diff(smaller, (a, b), o) for o in ((1, 0), (0, 1))]
        out.append(density(a, b))
    else:
        out = [sign * mpmath.diff(smaller, (a, b), o) for o in ((2, 0), (1, 1), (0, 2))]
        out += [mpmath.diff(density, (a, b), o) for o in ((1, 0), (0, 1))]
        out.append(mpmath.diff(lambda x_: density(a, b, x_), x))
    return [float(v) for v in out]


def _reference_table(name):
    import betainc_reference

    return np.array(getattr(betainc_reference, name), dtype=np.float64)


def _write_reference_table(path):
    header = (
        '"""40-digit mpmath references for test_special.py.\n\n'
        "Generated by ``PYTHONPATH=src python tests/util/test_special.py``.\n"
        '"""\n\n'
    )
    with open(path, "w") as f:
        f.write(header)
        for name, points, order, columns in (
            ("FIRST_ORDER", _first_order_points(), 1, "I, I_a, I_b, I_x"),
            ("SECOND_ORDER", _second_order_points(), 2, "I_aa, I_ab, I_bb, I_ax, I_bx, I_xx"),
        ):
            f.write(f"# a, b, x, {columns}\n{name} = (\n")
            for a, b, x in points:
                row = (a, b, x, *_mpmath_partials(a, b, x, order))
                f.write("    (" + ", ".join(repr(float(v)) for v in row) + "),\n")
            f.write(")\n\n")


def _value_and_partials(a, b, x):
    """Values and (a, b, x)-gradients for 1-d inputs."""
    value, grads = jax.jit(jax.vmap(jax.value_and_grad(betainc, argnums=(0, 1, 2))))(a, b, x)
    return (np.asarray(value), *(np.asarray(g) for g in grads))


def _assert_rel_close(got, want, rtol, what, scale=0.0):
    """|got - want| <= rtol * (|want| + scale), elementwise."""
    err = np.abs(got - want)
    bound = rtol * (np.abs(want) + scale) + 1e-300
    worst = np.argmax(err / bound)
    assert np.all(err <= bound), (
        f"{what}: err {err[worst]:.2e} vs bound {bound[worst]:.2e} at row {worst} "
        f"(got {got[worst]!r}, want {want[worst]!r})"
    )


