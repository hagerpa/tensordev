"""Tables of the "Benchmarks" section of the documentation page "Performance".

Run from the repository root:

    python docs/scripts/benchmarks.py

It reads the JSON files written by the benchmark scripts and writes docs/generated/bidegree.md and
docs/generated/wordwise_gpu.md:

    benchmarks/results/bidegree_efficiency.json   from benchmarks/bidegree_efficiency.py --output ...
    benchmarks/results/wordwise_gpu.json          from benchmarks/wordwise_gpu.py --output ...

It runs no benchmark and imports neither JAX nor tensordev.  Every number it writes is a value of the
JSON file, converted from seconds to milliseconds, or a ratio that the JSON file stores.  When a JSON
file is missing, the page gets a note that says how to produce it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "benchmarks" / "results"
OUT = ROOT / "docs" / "generated"
HEADER = "<!-- Generated by docs/scripts/benchmarks.py; do not edit. -->"

BIDEGREE_MISSING = """\
!!! note "No results yet"

    These tables are generated from `benchmarks/results/bidegree_efficiency.json`, which does not
    exist yet. Run `benchmarks/bidegree_efficiency.py` with `--output benchmarks/results/bidegree_efficiency.json`,
    then `python docs/scripts/benchmarks.py`.
"""

WORDWISE_MISSING = """\
!!! note "GPU measurements pending"

    These tables are generated from `benchmarks/results/wordwise_gpu.json`, which does not exist
    yet. The measurements need an NVIDIA GPU with compute capability 8.0 or newer. Run
    `benchmarks/wordwise_gpu.py` with `--output benchmarks/results/wordwise_gpu.json`, then
    `python docs/scripts/benchmarks.py`.
"""

EMPTY = """\
!!! note "{title}"

    `benchmarks/results/{source}` contains no {what}. Run `benchmarks/{script}` with
    `--output benchmarks/results/{source}`, then `python docs/scripts/benchmarks.py`.
"""

DASH = "–"


def table(header, rows, align=None):
    align = align or ["---"] * len(header)
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(align) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def ms(seconds):
    """Seconds from the JSON as milliseconds, three significant digits up to 1000 ms."""
    if seconds is None:
        return DASH
    value = 1e3 * float(seconds)
    if value >= 100:
        return f"{value:,.0f}"
    if value >= 10:
        return f"{value:.1f}"
    if value >= 1:
        return f"{value:.2f}"
    return f"{value:.3f}"


def calls(count, what):
    return f"{count} {what} call" + ("" if count == 1 else "s")


def ratio(value):
    return DASH if value is None else f"{float(value):.2f}"


def truncation(value):
    return f"({value[0]}, {value[1]})" if isinstance(value, list) else str(value)


# --- bidegree_efficiency.json -------------------------------------------------------------------

WORKLOADS = {"signature": "Signature", "volterra": "Volterra signature"}


def _rows_by_key(rows):
    by_key = {}
    for row in rows:
        key = (row["scenario"], row["workload"], row["mode"], row["kind"])
        if key in by_key:
            raise ValueError(f"duplicate row {key} in bidegree_efficiency.json")
        by_key[key] = row
    return by_key


def _comparison_label(total, bidegree):
    label = f"total {truncation(total['truncation'])} vs {truncation(bidegree['truncation'])}"
    return label if total["comparison_is_matched_max_order"] else label + ", non-equivalent"


def _workload_label(row):
    return f"{WORKLOADS.get(row['workload'], row['workload'])}, {row['steps']} increments"


def _order(rows):
    """Group rows by workload, then comparison, in the order they first appear."""
    workloads = list(dict.fromkeys(row["workload"] for row in rows))
    scenarios = list(dict.fromkeys(row["scenario"] for row in rows))
    return lambda row: (workloads.index(row["workload"]), scenarios.index(row["scenario"]))


def render_bidegree(doc):
    meta, rows, comparisons = doc["metadata"], doc["rows"], doc["comparisons"]
    if not comparisons:
        return EMPTY.format(title="No results yet", source="bidegree_efficiency.json",
                            what="comparisons", script="bidegree_efficiency.py")
    by_key = _rows_by_key(rows)

    order = _order(rows)
    warm = []
    for c in sorted(comparisons, key=order):
        total = by_key[(c["scenario"], c["workload"], c["mode"], "total")]
        bidegree = by_key[(c["scenario"], c["workload"], c["mode"], "bidegree")]
        warm.append([
            _workload_label(total),
            _comparison_label(total, bidegree),
            f"`{c['mode']}`",
            f"{total['output_elements']:,} / {bidegree['output_elements']:,}",
            ms(total["warm_median_s"]),
            ms(bidegree["warm_median_s"]),
            ratio(c["total_over_bidegree_warm_speedup"]),
        ])

    # A core that takes part in two comparisons (--include-mismatched) has one row per comparison;
    # the label then names the other core of the comparison.
    scenarios_of = {}
    for row in rows:
        config = (row["workload"], row["kind"], truncation(row["truncation"]))
        scenarios_of.setdefault(config, set()).add(row["scenario"])
    other = {"total": "bidegree", "bidegree": "total"}

    cold = []
    seen = []
    for row in sorted(rows, key=order):
        key = (row["scenario"], row["workload"], row["kind"])
        if key in seen:
            continue
        seen.append(key)
        direct = by_key.get((row["scenario"], row["workload"], "direct", row["kind"]))
        jit = by_key.get((row["scenario"], row["workload"], "outer-jit", row["kind"]))
        core = f"{row['kind']} {truncation(row['truncation'])}"
        if len(scenarios_of[(row["workload"], row["kind"], truncation(row["truncation"]))]) > 1:
            partner = next(r for r in rows if r["scenario"] == row["scenario"]
                           and r["workload"] == row["workload"] and r["kind"] == other[row["kind"]])
            core += f" (vs {truncation(partner['truncation'])})"
        cold.append([
            _workload_label(row),
            core,
            ms(direct["first_execution_s"]) if direct else DASH,
            ms(jit["lower_s"]) if jit else DASH,
            ms(jit["compile_s"]) if jit else DASH,
            ms(jit["first_execution_s"]) if jit else DASH,
        ])

    right = "--:"
    out = [
        f"Warm calls: medians of {calls(meta['repeats'], 'timed')} after "
        f"{calls(meta['warmups'], 'warm-up')}, in milliseconds. The payload counts the "
        "coordinates of the output, including the scalar. The ratio is the total-degree time "
        "divided by the bidegree time; above 1 the bidegree core is faster.",
        "",
        table(["Workload", "Comparison", "Mode", "Payload, total / bidegree", "Total degree",
               "Bidegree", "Ratio"], warm, ["---"] * 3 + [right] * 4),
        "",
        "First call and compilation, in milliseconds. In `direct` mode the first call includes "
        "the compilation done inside the call; in `outer-jit` mode lowering and compilation are "
        "timed before the first call.",
        "",
        table(["Workload", "Core", "`direct`: first call", "`outer-jit`: lowering", "compilation",
               "first call"], cold, ["---"] * 2 + [right] * 4),
        "",
        f"Machine: {meta['platform']}, JAX backend {meta['jax_backend']} "
        f"({', '.join(meta['devices'])}); Python {meta['python_version']}, JAX {meta['jax_version']}, "
        f"jaxlib {meta['jaxlib_version']}; {meta['dtype']}, preset `{meta['preset']}`, Volterra "
        f"scheme `{meta['volterra_scheme']}`"
        + (", JAX caches cleared before every row." if meta.get("clear_caches_between_rows") else "."),
    ]
    return "\n".join(out) + "\n"


# --- wordwise_gpu.json --------------------------------------------------------------------------

NATIVE = {"ordinary": "forced-pallas-jit", "fssk": "forced-private-native-jit"}
PORTABLE = "forced-portable-jit"
AUTOMATIC = "automatic-public-eager"


def _case_label(case):
    if case["workload"] == "ordinary":
        label = "Signature"
    else:
        label = f"FSSK {case['fssk_output']}"
        if case.get("coefficient_mode") not in (None, "uniform"):
            label += f", {case['coefficient_mode']} coefficients"
        if case.get("initial_state") not in (None, "zero"):
            label += f", {case['initial_state']} seed"
    return label


def _case_columns(case):
    blocks = case["block_mode"]
    if case.get("block_size") is not None:
        blocks += f", {case['block_size']}"
    core = f"{case['family']} {truncation(case['truncation'])}"
    return [_case_label(case), core, case["dtype"], blocks]


def _warm_median(measurement):
    warm = measurement["timing"]["warm"]
    return None if warm is None else warm["median_seconds"]


def _gate(gate):
    estimate = gate["native_to_portable_ratio"]["estimate"]
    low, high = gate["native_to_portable_ratio"]["confidence_interval_95"]
    return f"{ratio(estimate)} ({ratio(low)}–{ratio(high)})", "passed" if gate["passed"] else "failed"


def render_wordwise(doc):
    meta, cases = doc["metadata"], doc["cases"]
    if not cases:
        return EMPTY.format(title="GPU measurements pending", source="wordwise_gpu.json",
                            what="cases", script="wordwise_gpu.py")
    config = meta["configuration"]

    warm, cold = [], []
    for case in cases:
        runs = case["measurements"]
        native, portable = runs[NATIVE[case["workload"]]], runs[PORTABLE]
        automatic = runs.get(AUTOMATIC)
        estimate, passed = _gate(case["native_portable_warm_gate"])
        warm.append(_case_columns(case) + [
            ms(_warm_median(native)),
            ms(_warm_median(portable)),
            ms(_warm_median(automatic)) if automatic else DASH,
            estimate,
            f"{native['correctness']['maximum_absolute_error']:.1e}",
            passed,
        ])
        cold.append(_case_columns(case) + [
            ms(native["timing"]["trace_lower_seconds"]),
            ms(native["timing"]["compile_seconds"]),
            ms(portable["timing"]["trace_lower_seconds"]),
            ms(portable["timing"]["compile_seconds"]),
            ms(automatic["timing"]["first_execution_seconds"]) if automatic else DASH,
        ])

    thresholds = cases[0]["native_portable_warm_gate"]["thresholds"] if cases else None
    gate = "" if thresholds is None else (
        " The gate passes when the native median is at least "
        f"{100 * thresholds['minimum_median_speedup_fraction']:g}% below the portable median and "
        "the upper end of the interval is at least "
        f"{100 * thresholds['minimum_confidence_lower_bound_fraction']:g}% below 1.")
    device = meta["selected_device"]
    capability = device.get("compute_capability")
    capability = DASH if capability is None else ".".join(str(part) for part in capability)
    right = "--:"
    out = [
        f"Warm calls: medians of {calls(config['repeats'], 'timed')} after "
        f"{calls(config['warmups'], 'warm-up')}, in milliseconds, for a batch of "
        f"{config['batch']} paths with {config['steps']} increments. Native and portable calls "
        "are compiled with `jax.jit` and alternate; the automatic call is the public function "
        "called eagerly. The ratio is the native median divided by the portable median, with its "
        "paired bootstrap 95% interval; below 1 the wordwise kernel is faster. The error is the "
        "largest absolute difference from the portable result." + gate,
        "",
        table(["Workload", "Core", "dtype", "Blocks", "Native", "Portable", "Automatic",
               "Native / portable", "Error", "Gate"], warm, ["---"] * 4 + [right] * 5 + ["---"]),
        "",
        "Lowering and compilation of the jitted calls, and the first automatic call, which "
        "includes its compilation, in milliseconds.",
        "",
        table(["Workload", "Core", "dtype", "Blocks", "Native: lowering", "compilation",
               "Portable: lowering", "compilation", "Automatic: first call"], cold,
              ["---"] * 4 + [right] * 5),
        "",
        f"Device: {device['device_kind']} (compute capability {capability}, "
        f"{device['platform_version']}); host {meta['host_platform']}; Python {meta['python_version']}, "
        f"tensordev {meta['tensordev_version']}, JAX {meta['jax_version']}, jaxlib "
        f"{meta['jaxlib_version']}, NumPy {meta['numpy_version']}; recorded "
        f"{meta['timestamp_utc'][:10]}.",
    ]
    return "\n".join(out) + "\n"


# --- main ---------------------------------------------------------------------------------------

PAGES = [
    ("bidegree_efficiency.json", "bidegree.md", render_bidegree, BIDEGREE_MISSING),
    ("wordwise_gpu.json", "wordwise_gpu.md", render_wordwise, WORDWISE_MISSING),
]


def generate(results=RESULTS):
    """Return {output file name: Markdown} for every generated table file."""
    pages = {}
    for source, target, render, missing in PAGES:
        path = results / source
        if path.exists():
            try:
                body = render(json.loads(path.read_text(encoding="utf-8")))
            except (KeyError, TypeError, ValueError) as error:
                raise SystemExit(f"{path}: unexpected format ({type(error).__name__}: {error})")
        else:
            body = missing
        pages[target] = f"{HEADER}\n{body}"
    return pages


def main():
    for target, text in generate().items():
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / target).write_text(text, encoding="utf-8")
        print(f"wrote {(OUT / target).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
